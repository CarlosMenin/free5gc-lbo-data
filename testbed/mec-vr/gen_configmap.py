#!/usr/bin/env python3
"""
Generates the 'vr-app' ConfigMap with the scripts of the VR application for a namespace.

The sources live only here (testbed/mec-vr/); the YAML in
free5gc/mec/vr-app.yaml is DERIVED -- editing the YAML by hand guarantees that
the two copies diverge. After changing the .py files, run:

    python3 gen_configmap.py --all

Single use:
    python3 gen_configmap.py --namespace free5gc --out ../free5gc/mec/vr-app.yaml
"""
import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = ["vrclock.py", "vr_server.py", "vr_client.py"]
TARGETS = [("free5gc", "../free5gc/mec/vr-app.yaml")]

HEADER = """# GENERATED by testbed/mec-vr/gen_configmap.py -- DO NOT EDIT BY HAND.
# Source: testbed/mec-vr/{sources}
# checksum of the sources: {digest}
#
# Scripts of the VR application (the "VR-inspired" load of the initial design) mounted at /opt/vr:
#   vr_server.py  runs in mec-app (edge) and in remote-app (core)
#   vr_client.py  runs in the UERANSIM tester pod, through the IP of the UE tunnel
#   vrclock.py    module shared by both: kernel timestamps
#
# 'import vrclock' works because the three land in the SAME directory (/opt/vr)
# and Python puts the directory of the script in sys.path.
#
# They are mounted as a ConfigMap on purpose: no registry or image build is
# needed, and changing the code is 'kubectl apply' + a pod restart.
apiVersion: v1
kind: ConfigMap
metadata:
  name: vr-app
  namespace: {ns}
  labels:
    app: vr-app
data:
"""


def build(ns):
    blobs = []
    digest = hashlib.sha256()
    for name in SOURCES:
        body = open(os.path.join(HERE, name)).read()
        digest.update(body.encode())
        indented = "\n".join(("    " + l) if l.strip() else ""
                             for l in body.rstrip("\n").split("\n"))
        blobs.append(f"  {name}: |\n{indented}\n")
    head = HEADER.format(ns=ns, sources=" ".join(SOURCES),
                         digest=digest.hexdigest()[:16])
    return head + "".join(blobs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--namespace")
    ap.add_argument("--out")
    ap.add_argument("--all", action="store_true",
                    help="regenerates the ConfigMap of the free5gc testbed")
    args = ap.parse_args()

    jobs = TARGETS if args.all else [(args.namespace, args.out)]
    if not args.all and not (args.namespace and args.out):
        ap.error("use --all or (--namespace and --out)")

    for ns, out in jobs:
        path = out if os.path.isabs(out) else os.path.join(HERE, out)
        with open(path, "w") as fh:
            fh.write(build(ns))
        print(f"written {os.path.normpath(path)} (namespace {ns})")


if __name__ == "__main__":
    main()
