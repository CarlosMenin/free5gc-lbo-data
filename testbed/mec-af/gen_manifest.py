#!/usr/bin/env python3
"""
Generates the manifest of mec-af (the Traffic Influence AF) with the code embedded.

The source lives only here (testbed/mec-af/mec_af.py); the YAML in
free5gc/mec/mec-af.yaml is DERIVED -- same convention as vr-app. After
changing the .py, run:

    python3 gen_manifest.py
    kubectl apply -f ../free5gc/mec/mec-af.yaml
    kubectl -n free5gc rollout restart deploy/mec-af
"""
import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = "mec_af.py"
OUT = "../free5gc/mec/mec-af.yaml"

TEMPLATE = """# GENERATED by testbed/mec-af/gen_manifest.py -- DO NOT EDIT BY HAND.
# Source: testbed/mec-af/{source}
# checksum of the source: {digest}
#
# mec-af: the Application Function (AF) of the testbed. It resolves by DNS the services
# listed in SERVICES and keeps, for each one, a Traffic Influence subscription
# at the NEF -- this is how the (dynamic) ClusterIP of the MEC service
# reaches the I-UPF as a local breakout rule, with no literal in ueRouting.yaml.
#
#   mec-app.<ns>.svc.cluster.local --DNS--> mec-af --Nnef_TrafficInfluence-->
#           NEF --> UDR --> PCF --> SMF (DNAI=mec) --PFCP--> I-UPF
#
# No ServiceAccount/Role/RoleBinding on purpose: the AF does not talk to the
# Kubernetes API, only to CoreDNS -- the same source of truth that smfcfg already
# uses to find the UPFs. So it does not depend on RBAC permissions.
#
# Depends on: nef (common/nef.yaml) and the DNAI "mec" declared at the I-UPF
# (scenario-b-dupf/smf.yaml). State at http://mec-af:8080/status.
apiVersion: v1
kind: ConfigMap
metadata:
  name: mec-af
  namespace: {ns}
  labels:
    app: mec-af
data:
  {source}: |
{code}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: mec-af
  namespace: {ns}
  labels:
    app: mec-af
spec:
  replicas: 1
  # Recreate, not RollingUpdate: mec-af is a singleton controller, and two
  # of them running at the same time compete for the same subscriptions at the NEF.
  strategy:
    type: Recreate
  selector:
    matchLabels:
      app: mec-af
  template:
    metadata:
      labels:
        app: mec-af
    spec:
      # MEC DOMAIN of the EDGE NODE, next to mec-app.
      #
      # The AF is not an NF of the 5GC: it is the application function of the MEC domain,
      # which is why it talks to the core through the NEF (Nnef_TrafficInfluence) and not
      # directly to the PCF -- the third-party AF model, outside the trusted domain
      # of the operator. In the design of the testbed it sits inside the "MEC Domain" box of
      # the Edge Node, not inside the "Server Node (5G Core)"; leaving it in the core
      # would erase that boundary.
      #
      # It does not touch the data plane or what is measured: the AF resolves DNS and makes
      # a few HTTP calls at startup, then only keeps the subscription alive. The
      # Traffic Influence request crosses the backhaul to the NEF, as the architecture
      # requires -- if this call fails, the symptom shows up in step 11
      # of the test as "LBO IS NOT ACTIVE".
      #
      # nodetype: the small edge machines are 'computer', not 'server' -- hence no selector.
      nodeSelector:
        kubernetes.io/arch: amd64
        kubernetes.io/hostname: brix-porvir-05
        #nodetype: server
      volumes:
        - name: code
          configMap:
            name: mec-af
      containers:
        - name: mec-af
          image: python:3.12-slim
          command: ["python3", "-u", "/opt/af/{source}"]
          env:
            - name: NS
              value: "{ns}"
            # Edge services announced to the NEF. A short name becomes
            # <name>.<ns>.svc.cluster.local. remote-app stays OUT: it is
            # the counterpoint of the measurement and must keep going up to the PSA-UPF.
            - name: SERVICES
              value: "mec-app"
            - name: NEF_URL
              value: "http://nef.{ns}.svc.cluster.local:8000"
            # Only to delete orphan records left by a restarted NEF.
            - name: UDR_URL
              value: "http://udr.{ns}.svc.cluster.local:8000"
            - name: AF_ID
              value: "af001"
            - name: DNN
              value: "internet"
            # Only the slice of the experiment (the UE of the tester uses 010203). 112233
            # is that of the background UE (background/background-gtp.yaml): in Scenario B the
            # I-UPF does not serve it, and a breakout rule in it would have no UPF
            # with the DNAI -- the SMF would fail the ApplyPccRules of the background session.
            # This is the value of the manifest that ran in the experiment (validate.py checks it).
            - name: SNSSAIS
              value: "1:010203"
            # Union of the pools of the PSA-UPF (60.60.0.0/17 + 60.60.128.0/17).
            - name: UE_CIDR
              value: "60.60.0.0/16"
            # Must be the same dnaiList as the I-UPF in scenario-b-dupf/smf.yaml.
            - name: DNAI
              value: "mec"
            - name: NOTIFY_URL
              value: "http://mec-af.{ns}.svc.cluster.local:8080/notify"
            # DNS polling. The ClusterIP only changes when the Service is
            # recreated, so 10 s is plenty before the campaign starts.
            - name: POLL_S
              value: "10"
          ports:
            - name: http-8080
              protocol: TCP
              containerPort: 8080
          volumeMounts:
            - name: code
              mountPath: /opt/af
              readOnly: true
          readinessProbe:
            httpGet:
              path: /healthz
              port: 8080
            initialDelaySeconds: 3
            periodSeconds: 10
---
apiVersion: v1
kind: Service
metadata:
  name: mec-af
  namespace: {ns}
  labels:
    app: mec-af
spec:
  selector:
    app: mec-af
  ports:
    - name: http-8080
      protocol: TCP
      port: 8080
      targetPort: 8080
"""


def build(ns):
    body = open(os.path.join(HERE, SOURCE)).read()
    digest = hashlib.sha256(body.encode()).hexdigest()[:16]
    code = "\n".join(("    " + l) if l.strip() else ""
                     for l in body.rstrip("\n").split("\n"))
    return TEMPLATE.format(ns=ns, source=SOURCE, digest=digest, code=code)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--namespace", default="free5gc")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()
    path = args.out if os.path.isabs(args.out) else os.path.join(HERE, args.out)
    with open(path, "w") as fh:
        fh.write(build(args.namespace))
    print(f"written {os.path.normpath(path)} (namespace {args.namespace})")


if __name__ == "__main__":
    main()
